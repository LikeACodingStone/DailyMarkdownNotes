#!/usr/bin/env python3
"""Scan gist_code and rebuild gist-url-for-copy.md: a table of Gist links with copy buttons."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
GIST_DIR = ROOT / 'gist_code'
OUTPUT = ROOT / 'scripts' / 'gist-url-for-copy.md'

# Rendered by the Dataview plugin (needs Settings > Dataview > Enable JavaScript Queries).
PAGE = '''<!-- Generated by scripts/py_absort_gist_url.py from gist_code/. Do not edit; it is overwritten on every run. -->

```dataviewjs
const links = __LINKS__;

const copyButton = (text) => {
  const button = document.createElement("button");
  button.textContent = "Copy";
  button.addEventListener("click", async () => {
    try {
      await navigator.clipboard.writeText(text);
      button.textContent = "Copied";
    } catch (error) {
      console.error(error);
      button.textContent = "Failed";
    }
    setTimeout(() => { button.textContent = "Copy"; }, 1500);
  });
  return button;
};

dv.table(["Link", "Copy"], links.map((text) => [text, copyButton(text)]));
```
'''


def gist_markdown(path):
    """Return a Markdown link from the note's Share as Gist metadata."""
    content = path.read_text(encoding='utf-8-sig')
    frontmatter = re.match(r'\A---\s*\n(.*?)\n---\s*(?:\n|$)', content, re.S)
    if not frontmatter:
        raise ValueError('No Gist metadata found. Share this note using Share as Gist first.')
    # Share as Gist writes a block-style gists list. Ignore links in the body.
    lines = frontmatter.group(1).splitlines()
    in_gists = False
    urls = []
    for line in lines:
        if re.fullmatch(r'gists:\s*', line):
            in_gists = True
            continue
        if in_gists and re.match(r'^[^\s#-]', line):
            break
        if in_gists:
            match = re.match(r'''^\s+(?:-\s+)?url:\s*['"]?(https://gist\.github\.com/[A-Za-z0-9_-]+/[a-fA-F0-9]+)['"]?\s*(?:#.*)?$''', line)
            if match and match.group(1) not in urls:
                urls.append(match.group(1))
    if not urls:
        raise ValueError('No valid GitHub Gist URL found in the gists metadata.')
    if len(urls) > 1:
        raise ValueError('Multiple Gist URLs found; cannot choose one: ' + ', '.join(urls))
    label = re.sub(r'([\\\[\]])', r'\\\1', path.stem)
    return f'[{label}]({urls[0]})'


def collect_links(folder=GIST_DIR):
    """Return (links, skipped): one Markdown link per note, and (note, reason) for notes without one."""
    if not folder.is_dir():
        raise FileNotFoundError(f'Folder not found: {folder}')
    notes = sorted((p for p in folder.rglob('*.md') if p.is_file()),
                   key=lambda p: p.relative_to(folder).as_posix().casefold())
    links, skipped = [], []
    for note in notes:
        try:
            links.append(gist_markdown(note))
        except (OSError, ValueError) as error:
            skipped.append((note.relative_to(folder).as_posix(), error))
    return links, skipped


def render_page(links):
    """Return the Markdown page: a Dataview table with a copy button for each link."""
    return PAGE.replace('__LINKS__', json.dumps(links, ensure_ascii=False, indent=2))


def main():
    try:
        links, skipped = collect_links()
    except OSError as error:
        print(f'FAILURE: {error}', flush=True)
        return 1
    for name, reason in skipped:
        print(f'SKIPPED: {name}: {reason}', flush=True)
    if not links:
        print(f'FAILURE: No Gist links found in {GIST_DIR.name}; {OUTPUT.name} was not changed.', flush=True)
        return 1
    try:
        with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as file:
            file.write(render_page(links))
    except OSError as error:
        print(f'FAILURE: {error}', flush=True)
        return 1
    print(f'SUCCESS: {len(links)} link(s) written to {OUTPUT.name}.', flush=True)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
